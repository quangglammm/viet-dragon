import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { createSeededDatabase, type SeededDatabase } from "@/tests/helpers/seeded-db";
import { LOCALES, localizedText, translated } from "./localized";
import { linkedProductPaths, resolveSegment, segmentCandidates } from "./resolve";
import { groupBy } from "./util";

// URL and menu parity: the URLs the old pages accepted still resolve to the same targets, and the menus can be
// rebuilt from the database exactly as the original files define them.

let seeded: SeededDatabase;
beforeAll(async () => {
  seeded = await createSeededDatabase("parity_urls");
}, 120_000);
afterAll(async () => {
  await seeded.close();
});

const rows = async <T extends object>(sql: string): Promise<T[]> => (await seeded.scratch.pool.query(sql)).rows as T[];
const products = () => [...seeded.outcome.products.values()];

describe("URLs (checked in every language)", () => {
  // The old pages accepted a set of segments for a product; the same URLs must still reach the same target in every
  // language — except where a language's NEW canonical slug is the same text, which belongs to its own entity.
  // BY CONSTRUCTION: the aliases were generated by the same resolver over the same candidates.
  it("resolve every candidate segment of every product like the old page did, in every language", async () => {
    const segments = await rows<{ product_id: number; locale: string; slug: string; shape_id: number | null; option_id: number | null; is_canonical: boolean }>(
      `select product_id, locale, slug, shape_id, option_id, is_canonical from product_segment`,
    );
    const byKey = new Map(segments.map((r) => [`${r.product_id}|${r.locale}|${r.slug}`, r]));
    const target = (row: (typeof segments)[number] | undefined) => (row ? (row.shape_id !== null ? `shape:${row.shape_id}` : `option:${row.option_id}`) : null);
    let checked = 0;
    const differences: string[] = [];
    const takenByNewCanonical: string[] = [];
    for (const product of products()) {
      for (const locale of LOCALES) {
        for (const segment of segmentCandidates(seeded.src, product)) {
          const old = resolveSegment(seeded.src, product, segment);
          const wanted = old ? (old.kind === "shape" ? `shape:${old.shape.id}` : `option:${old.option.id}`) : null;
          const row = byKey.get(`${product.id}|${locale}|${segment}`);
          checked += 1;
          if (row?.is_canonical && target(row) !== wanted) takenByNewCanonical.push(`${product.key} ${locale} ${segment}`);
          else if (target(row) !== wanted) differences.push(`${product.key} ${locale} ${segment}`);
        }
      }
    }
    expect(checked).toBeGreaterThan(20000);
    expect(differences).toEqual([]);
    expect(takenByNewCanonical).toEqual([]); // a language's new canonical slug never shadows an old URL of another entity
  });

  it("resolve product URLs like getSubgroupById in every language, except the synthetic cross-category ones", async () => {
    const slugs = await rows<{ locale: string; category_id: string; slug: string; product_id: number }>(`select locale, category_id, slug, product_id from product_slug`);
    const bySlug = new Map(slugs.map((r) => [`${r.locale}|${r.category_id}/${r.slug}`, Number(r.product_id)]));
    const linked = linkedProductPaths(seeded.src);
    const { src } = seeded;
    const candidateIds = new Set([...src.subgroups.map((s) => s.id), ...Object.keys(src.subgroupAliases)]);
    const canonicalIn = (locale: string, categoryId: string, slug: string) => products().find((p) => p.source.categoryId === categoryId && p.slugs[locale as keyof typeof p.slugs] === slug);
    const bad: string[] = [];
    for (const locale of LOCALES) {
      for (const category of src.categories) {
        for (const id of candidateIds) {
          const target = src.getSubgroupById(id, category.id);
          const expectsRow = target !== undefined && (target.categoryId === category.id || linked.has(`${category.id}/${id}`));
          const got = bySlug.get(`${locale}|${category.id}/${id}`);
          const owner = canonicalIn(locale, category.id, id); // a new canonical slug with the same text wins
          const want = owner ? owner.id : expectsRow ? seeded.outcome.products.get(`${target.categoryId}/${target.id}`)!.id : undefined;
          if (got !== want) bad.push(`${locale} ${category.id}/${id}`);
        }
      }
    }
    expect(bad).toEqual([]);
  });

  // INDEPENDENT: the inventory comes from scanning the source for "/products/…" string literals, not from any resolver.
  // Each literal is a URL that works today; it must still resolve in EVERY language (category, product, then segment).
  it("resolve every /products/… link found in the source (127 of them) in every language", async () => {
    const categories = await rows<{ locale: string; slug: string; category_id: string }>(`select locale, slug, category_id from category_slug`);
    const slugs = await rows<{ locale: string; category_id: string; slug: string; product_id: number }>(`select locale, category_id, slug, product_id from product_slug`);
    const segments = await rows<{ product_id: number; locale: string; slug: string }>(`select product_id, locale, slug from product_segment`);
    const categoryOf = new Map(categories.map((r) => [`${r.locale}|${r.slug}`, r.category_id]));
    const productOf = new Map(slugs.map((r) => [`${r.locale}|${r.category_id}|${r.slug}`, Number(r.product_id)]));
    const segmentSet = new Set(segments.map((r) => `${r.product_id}|${r.locale}|${r.slug}`));
    const unresolved: string[] = [];
    for (const [href, file] of seeded.src.productLinks) {
      const [path, hash] = href.split("#");
      const parts = path.split("/").filter(Boolean); // products, category, product, segment
      if (parts.length <= 2 || parts[1] === "fast-print") {
        if (parts.length === 2 && parts[1] !== "fast-print") for (const locale of LOCALES) if (!categoryOf.has(`${locale}|${parts[1]}`)) unresolved.push(`${href} (${file}) — category in ${locale}`);
        continue;
      }
      for (const locale of LOCALES) {
        const categoryId = categoryOf.get(`${locale}|${parts[1]}`);
        const productId = categoryId ? productOf.get(`${locale}|${categoryId}|${parts[2]}`) : undefined;
        const segment = parts[3] ?? hash;
        if (!categoryId) unresolved.push(`${href} (${file}) — category in ${locale}`);
        else if (productId === undefined) unresolved.push(`${href} (${file}) — product in ${locale}`);
        else if (segment && !segmentSet.has(`${productId}|${locale}|${segment}`)) unresolved.push(`${href} (${file}) — segment '${segment}' in ${locale}`);
      }
    }
    expect(seeded.src.productLinks.size).toBe(127); // 130 before Phase 4 moved the chrome to the database and rewrote the examples in lib/menu-active.ts
    expect(unresolved).toEqual([]);
  });
});

describe("menus", () => {
  it("can be rebuilt from the database exactly as the original files define them", async () => {
    const { src } = seeded;
    const num = (v: number | string) => Number(v);
    const groups = (await rows<{ product_id: number; menu_column: number; position: number; category_id: string; gimg: string | null; pcover: string | null }>(
      `select g.product_id, g.menu_column, g.position, p.category_id, gm.storage_key gimg, pc.storage_key pcover from menu_group g join product p on p.id = g.product_id left join media gm on gm.id = g.image_media_id left join media pc on pc.id = p.cover_media_id`,
    ));
    const groupTexts = groupBy(await rows<{ product_id: number; locale: string; label: string | null; description: string | null }>(`select product_id, locale, label, description from menu_group_i18n`), (r) => num(r.product_id));
    const productTexts = new Map((await rows<{ product_id: number; locale: string; title: string; description: string | null }>(`select product_id, locale, title, description from product_i18n`)).map((r) => [`${r.product_id}|${r.locale}`, r]));
    const items = groupBy(
      await rows<{ id: number; product_id: number; position: number; is_fast: boolean; shape_id: number | null; option_id: number | null; img: string | null; shape_img: string | null }>(
        `select i.id, i.product_id, i.position, i.is_fast, i.shape_id, i.option_id, im.storage_key img, sm.storage_key shape_img from menu_item i left join media im on im.id = i.image_media_id left join shape s on s.id = i.shape_id left join media sm on sm.id = s.image_media_id`,
      ),
      (r) => num(r.product_id),
    );
    const itemTexts = groupBy(await rows<{ menu_item_id: number; locale: string; label: string }>(`select menu_item_id, locale, label from menu_item_i18n`), (r) => num(r.menu_item_id));
    const shapeNames = new Map((await rows<{ shape_id: number; locale: string; name: string }>(`select shape_id, locale, name from shape_i18n`)).map((r) => [`${r.shape_id}|${r.locale}`, r.name]));
    const optionNames = new Map((await rows<{ option_id: number; locale: string; name: string | null }>(`select option_id, locale, name from option_i18n`)).map((r) => [`${r.option_id}|${r.locale}`, r.name]));

    const noSlash = (path: string) => path.replace(/^\//, "");
    let checks = 0;
    const bad: string[] = [];
    const expectEqual = (label: string, got: unknown, want: unknown) => {
      checks += 1;
      if (got !== want) bad.push(`${label}: ${String(got)} ≠ ${String(want)}`);
    };

    for (const [categoryId, columns] of Object.entries(src.menus)) {
      const dbGroups = groups.filter((g) => g.category_id === categoryId).sort((a, b) => a.menu_column - b.menu_column || a.position - b.position);
      const srcGroups = columns.flatMap((column, ci) => column.groups.map((group, gi) => ({ group, ci, gi })));
      expectEqual(`${categoryId} group count`, dbGroups.length, srcGroups.length);
      for (const [k, { group, ci, gi }] of srcGroups.entries()) {
        const dg = dbGroups[k];
        if (!dg) continue;
        const productId = num(dg.product_id);
        expectEqual(`${group.id} column/position`, `${dg.menu_column}.${dg.position}`, `${ci + 1}.${gi}`);
        const overrides = new Map((groupTexts.get(productId) ?? []).map((r) => [r.locale, r]));
        for (const locale of LOCALES) {
          const want = localizedText(group, "title", "suffixed", locale);
          if (!want?.trim()) continue;
          expectEqual(`${group.id} title ${locale}`, overrides.get(locale)?.label ?? productTexts.get(`${productId}|${locale}`)?.title, want);
        }
        expectEqual(`${group.id} image`, dg.gimg ?? dg.pcover, noSlash(group.image));
        if (categoryId === "tet") {
          // The Tet category page lists GROUPS and shows ITEM_DESCS[group.id] — keyed by the group id.
          const sub = src.getSubgroupById(group.id, categoryId)!;
          for (const locale of LOCALES) {
            const want = locale === "vi" ? sub.descriptionVi : locale === "en" ? sub.descriptionEn : (translated(src.translations.ITEM_DESCS, group.id, locale) ?? sub.descriptionEn);
            const derived = productTexts.get(`${productId}|${locale}`)?.description ?? productTexts.get(`${productId}|en`)?.description;
            expectEqual(`${group.id} description ${locale}`, overrides.get(locale)?.description ?? derived, want);
          }
        }
        const dbItems = [...(items.get(productId) ?? [])].sort((a, b) => a.position - b.position);
        expectEqual(`${group.id} item count`, dbItems.length, group.items.length);
        for (const [ii, item] of group.items.entries()) {
          const di = dbItems[ii];
          if (!di) continue;
          const labels = new Map((itemTexts.get(num(di.id)) ?? []).map((r) => [r.locale, r.label]));
          expectEqual(`${item.id} Fast Print flag`, Boolean(di.is_fast), Boolean(item.isFast));
          for (const locale of LOCALES) {
            const want = localizedText(item, "name", "suffixed", locale);
            if (!want?.trim()) continue;
            const derived = di.shape_id ? shapeNames.get(`${di.shape_id}|${locale}`) : optionNames.get(`${di.option_id}|${locale}`);
            expectEqual(`${item.id} label ${locale}`, labels.get(locale) ?? derived, want);
          }
          expectEqual(`${item.id} image`, di.img ?? (di.shape_id ? di.shape_img : dg.pcover), noSlash(item.image));
        }
      }
    }
    expect(bad).toEqual([]);
    expect(checks).toBeGreaterThan(800);
  });
});
